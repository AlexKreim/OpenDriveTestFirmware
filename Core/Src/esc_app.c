static void cmd_get(const char *only)
{
    char b[96];
    if (only) {                                    /* 'get <name>': just that parameter */
        for (int i = 0; i < params_count(); i++) {
            if (!strcmp(params_name(i), only) && params_format(&g_par, i, b, sizeof(b)) > 0) { uprintf("%s", b); reply_ok(); return; }
        }
        reply_err("invalid");
        return;
    }
    for (int i = 0; i < params_count(); i++) {
        if (params_format(&g_par, i, b, sizeof(b)) > 0) uprintf("%s", b);
    }
    if (params_format_name(&g_par, b, sizeof(b)) > 0) uprintf("%s", b);
    reply_ok();
}

