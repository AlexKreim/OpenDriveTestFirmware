/* the calibration runs in the control interrupt; report the result as a machine readable line and store it in the parameters */
static bool cal_active;

static void cal_task(void)
{
    if (!cal_active) return;
    int st = motor_cal_status();
    if (st == 0) {
        if (g_state == ST_IDLE || g_state == ST_FAULT) { cal_active = false; uprintf("CAL,fail,%s\r\n", g_state == ST_FAULT ? "fault" : "aborted"); }
        return;
    }
    cal_active = false;
    float r, l, pp;
    int dir;
    const char *err = NULL;
    if (!motor_cal_result(&r, &l, &dir, &pp, &err)) { uprintf("CAL,fail,%s\r\n", err ? err : "unknown"); return; }
    float r_ll = 2000.0f * r, l_ll = 2.0e6f * l;
    bool ok = params_set(&g_par, "rl", r_ll) && params_set(&g_par, "ll", l_ll) && params_set(&g_par, "encdir", (float)dir);
    float ppr = floorf(pp + 0.5f);
    if (ok && fabsf(pp - ppr) < 0.3f) ok = params_set(&g_par, "pp", ppr);
    else if (ok) { params_derive(&g_par, g_vbus, &g_eff); uprintf("CAL,fail,pole_pairs\r\n"); return; }   /* not an integer: do not guess */
    params_derive(&g_par, g_vbus, &g_eff);
    if (ok) uprintf("CAL,ok,%s,%s,%d,%s\r\n", ff(r_ll), ff(l_ll), dir, ff(pp));
    else    uprintf("CAL,fail,%s\r\n", "range");
}

static void handle_line(char *line)
{
    char *sv;
    char *cmd = strtok_r(line, " \t", &sv);
    if (!cmd) return;
    char *a1 = strtok_r(NULL, " \t", &sv);
    char *a2 = strtok_r(NULL, " \t", &sv);

    if (!strcmp(cmd, "help")) {
        uprintf("help | status | get | test | diag | raw | gates | zero [ram] | start | stop | clear | enc [ms] | ver\r\n"
                "mode 0|1|2|3 (open loop|torque|speed|position) | tq <A> | pos <deg> | calibrate | focdump\r\n"
                "set <name> <value> | setname <text> | save | load | factory | stream <hz> | wd <ms> | ping | led r|g|b|off|auto | bemf 0|1\r\n");
        uprintf("names: pp six dir auto kv rpm accel boost maxmod ilim alignv alignms rl ll kt idrive rpmmax\r\n"
                "       curbw curkp curki curauto spdkp spdki poskp poski poskd posvmax posacc imax ialign ical otdrv otdrven otmot otmoten encdir\r\n");
    } else if (!strcmp(cmd, "led")) {
        if (!a1) { uprintf("led r|g|b|off|auto\r\n"); return; }
        if (!strcmp(a1, "auto")) { led_manual = false; uprintf("led auto\r\n"); return; }
        led_manual = true;
        if      (!strcmp(a1, "r"))   hw_led_set(hw_led_get() ^ 1u);
        else if (!strcmp(a1, "g"))   hw_led_set(hw_led_get() ^ 2u);
        else if (!strcmp(a1, "b"))   hw_led_set(hw_led_get() ^ 4u);
        else if (!strcmp(a1, "off")) hw_led_set(0);
        uprintf("led mask %u\r\n", hw_led_get());
    } else if (!strcmp(cmd, "status")) {
        print_status();
    } else if (!strcmp(cmd, "params") || !strcmp(cmd, "get")) {
        cmd_get(a1);
    } else if (!strcmp(cmd, "ver")) {
        uprintf("V,ESC,%s,%u,%u\r\n", ESC_FW_VERSION, (unsigned)PARAMS_VERSION, (unsigned)params_count());
    } else if (!strcmp(cmd, "ping")) {
        /* keep-alive only, last_rx_ms was refreshed when the bytes arrived */
    } else if (!strcmp(cmd, "stream")) {
        uint32_t hz = a1 ? (uint32_t)strtoul(a1, NULL, 10) : 0u;
        if (hz > 200u) { reply_err("range"); return; }
        stream_period = (hz == 0u) ? 0u : (1000u / hz);
        reply_ok();
    } else if (!strcmp(cmd, "wd")) {
        uint32_t ms = a1 ? (uint32_t)strtoul(a1, NULL, 10) : 0u;
        if (ms != 0u && (ms < 200u || ms > 10000u)) { reply_err("range"); return; }
        wd_ms = ms;
        last_rx_ms = HAL_GetTick();
        reply_ok();
    } else if (!strcmp(cmd, "save")) {
        if (motor_running()) { reply_err("motor_running"); return; }
        flash_res_t r = flash_save_params(&g_par);
        if (r == FLASH_RES_OK) { params_from_flash = true; reply_ok(); }
        else reply_err(r == FLASH_RES_ERASE ? "flash_erase" : (r == FLASH_RES_PROGRAM ? "flash_program" : "flash_verify"));
    } else if (!strcmp(cmd, "load")) {
        if (motor_running()) { reply_err("motor_running"); return; }
        flash_image_t img;
        if (flash_image_load(&img) && img.par_valid) { g_par = img.par; params_derive(&g_par, g_vbus, &g_eff); reply_ok(); }
        else reply_err("no_saved_data");
    } else if (!strcmp(cmd, "factory")) {
        if (motor_running()) { reply_err("motor_running"); return; }
        params_defaults(&g_par);
        params_derive(&g_par, g_vbus, &g_eff);
        reply_ok();                              /* RAM only, 'save' writes it to flash */
    } else if (!strcmp(cmd, "test")) {
        run_tests();
    } else if (!strcmp(cmd, "raw")) {
        /* ~200 ms of samples: a live sense chain shows noise of a few counts, a dead one shows min = max (or rails at 0 / 4095) */
        uint32_t sum[3] = {0, 0, 0};
        uint16_t mn[3] = {4095, 4095, 4095}, mx[3] = {0, 0, 0};
        const int N = 200;
        for (int k = 0; k < N; k++) {
            for (int i = 0; i < 3; i++) {
                uint16_t v = g_raw[i];
                sum[i] += v;
                if (v < mn[i]) mn[i] = v;
                if (v > mx[i]) mx[i] = v;
            }
            HAL_Delay(1);
        }
        for (int i = 0; i < 3; i++)
            uprintf("raw %c: mean %lu, min %u, max %u, offset in use %s counts (%s A at mean)\r\n", 'A' + i,
                    (unsigned long)(sum[i] / N), (unsigned)mn[i], (unsigned)mx[i], ff(motor_offset_counts(i)),
                    ff(CS_SIGN * ((float)sum[i] / N - motor_offset_counts(i)) * (3.3f / 4095.0f) / CS_V_PER_A));
        uprintf("expected idle ~1350 counts (1.09 V); a mean near 0 or 4095 means the chain is saturated or not connected\r\n");
    } else if (!strcmp(cmd, "diag")) {
        print_diag();
    } else if (!strcmp(cmd, "gates")) {
        run_gate_test();
    } else if (!strcmp(cmd, "zero")) {
        /* zero [ram]: re-measure the current sensor offsets (no current may flow) and store them in flash */
        bool save = !(a1 && !strcmp(a1, "ram"));
        if (g_state == ST_FAULT) { reply_err("fault"); return; }
        if (g_state != ST_IDLE)  { reply_err("motor_running"); return; }
        if (!motor_calibrate_offsets()) { reply_err("cal_failed"); return; }
        float o[3], worst = 0.0f;
        for (int i = 0; i < 3; i++) {
            o[i] = motor_offset_counts(i);
            if (motor_cal_noise(i) > worst) worst = motor_cal_noise(i);
        }
        uprintf("zero: offsets A %s, B %s, C %s counts; noise p-p %s / %s / %s counts\r\n", ff(o[0]), ff(o[1]), ff(o[2]),
                ff(motor_cal_noise(0)), ff(motor_cal_noise(1)), ff(motor_cal_noise(2)));
        for (int i = 0; i < 3; i++)
            if (o[i] < ZERO_MIN_COUNTS || o[i] > ZERO_MAX_COUNTS) { reply_err("saturated"); return; }   /* op-amp pinned to a rail: never store that */
        if (worst > ZERO_MAX_NOISE) { reply_err("noisy"); return; }       /* in RAM only, never stored */
        offsets_from_flash = false;
        if (save) {
            flash_res_t r = flash_save_offsets(o);
            if (r != FLASH_RES_OK) { reply_err(r == FLASH_RES_ERASE ? "flash_erase" : (r == FLASH_RES_PROGRAM ? "flash_program" : "flash_verify")); return; }
            offsets_from_flash = true;
        }
        reply_ok();
    } else if (!strcmp(cmd, "start")) {
        const char *why = NULL;
        if (g_state == ST_FAULT)                                  why = "fault";
        else if (g_state != ST_IDLE)                              why = "not_idle";
        else if (!g_cal_done)                                     why = "no_cal";
        else if (g_vbus < VBUS_MIN_V || g_vbus > VBUS_MAX_V)      why = "bus_voltage";
        else if (g_mode != MODE_OPEN && g_par.enc_dir == 0)       why = "no_enc_cal";
        if (why) reply_err(why);
        else if (motor_start()) reply_ok();
        else reply_err("refused");
    } else if (!strcmp(cmd, "mode")) {
        if (!a1) { uprintf("mode %d\r\n", (int)g_mode); return; }
        int m = atoi(a1);
        if (motor_running()) { reply_err("motor_running"); return; }
        if (m < 0 || m > 3) { reply_err("range"); return; }
        g_mode = (esc_mode_t)m;
        reply_ok();
    } else if (!strcmp(cmd, "tq")) {
        if (!a1) { reply_err("usage"); return; }
        float v = strtof(a1, NULL);
        if (v != v || v > g_par.i_max || v < -g_par.i_max) { reply_err("range"); return; }
        g_tq_cmd = v;
        reply_ok();
    } else if (!strcmp(cmd, "pos")) {
        if (!a1) { reply_err("usage"); return; }
        float v = strtof(a1, NULL);
        if (v != v || v < 0.0f || v > 360.0f) { reply_err("range"); return; }
        g_pos_cmd = v;
        reply_ok();
    } else if (!strcmp(cmd, "calibrate")) {
        const char *why = NULL;
        if (g_state == ST_FAULT)                               why = "fault";
        else if (g_state != ST_IDLE)                           why = "not_idle";
        else if (!g_cal_done)                                  why = "no_cal";
        else if (g_vbus < VBUS_MIN_V || g_vbus > VBUS_MAX_V)   why = "bus_voltage";
        if (!why && !motor_cal_start())                        why = "refused";
        if (why) { reply_err(why); return; }
        cal_active = true;
        reply_ok();
    } else if (!strcmp(cmd, "focdump")) {
        /* the last 5 ms of FOC data before an overcurrent / encoder / overspeed fault (20 kHz samples) */
        float v[12];
        int n = motor_foc_log_count();
        uprintf("F,count,%d\r\n", n);
        for (int i = 0; i < n; i++) {
            if (!motor_foc_log(i, v)) break;
            uprintf("F,%d,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%u,%u\r\n", i, ff(v[0]), ff(v[1]), ff(v[2]), ff(v[3]), ff(v[4]), ff(v[5]), ff(v[6]), ff(v[7]), ff(v[8]), ff(v[9]), (unsigned)v[10], (unsigned)v[11]);
            HAL_Delay(3);
        }
        reply_ok();
    } else if (!strcmp(cmd, "enc")) {
        uint32_t per = a1 ? (uint32_t)strtoul(a1, NULL, 10) : 100u;
        if (per < 20u) per = 20u;
        if (per > 5000u) per = 5000u;
        enc_period = per;
        enc_last_abi = hw_enc_count();
        enc_total = 0;
        enc_stream = true;
        uprintf("encoder stream every %lu ms, send 'stop' to end it\r\n", (unsigned long)per);
    } else if (!strcmp(cmd, "stop")) {
        enc_stream = false;
        if (motor_running()) stop_reason = "'stop' command from the PC";
        motor_stop();
        reply_ok();
    } else if (!strcmp(cmd, "clear")) {
        motor_clear_fault();
        if (g_state == ST_IDLE) hw_as5047_reset();         /* re-initialise the encoder SPI after an encoder fault */
        reply_ok();
    } else if (!strcmp(cmd, "bemf")) {
        hw_bemf_enable(a1 && a1[0] == '1');
        uprintf("bemf divider %s\r\n", (a1 && a1[0] == '1') ? "on" : "off");
    } else if (!strcmp(cmd, "setname")) {
        /* setname <text>: name of the motor preset (rest of the line, spaces allowed) */
        char nm[PRESET_NAME_LEN + 8];
        nm[0] = 0;
        for (char *t = a1; t; t = (t == a1) ? a2 : strtok_r(NULL, " \t", &sv)) {
            if (strlen(nm) + strlen(t) + 2 > sizeof(nm)) { reply_err("invalid"); return; }
            if (nm[0]) strcat(nm, " ");
            strcat(nm, t);
        }
        if (!nm[0] || motor_running()) { reply_err(nm[0] ? "motor_running" : "usage"); return; }
        if (params_set_name(&g_par, nm)) reply_ok(); else reply_err("invalid");
    } else if (!strcmp(cmd, "set")) {
        if (!a1 || !a2) { reply_err("usage"); return; }
        if (motor_running() && (!strcmp(a1, "pp") || !strcmp(a1, "six") || !strcmp(a1, "dir") || !strcmp(a1, "encdir"))) {
            reply_err("motor_running");          /* these must not change while the motor is driven */
            return;
        }
        if (params_set(&g_par, a1, strtof(a2, NULL))) { params_derive(&g_par, g_vbus, &g_eff); reply_ok(); }
        else reply_err("invalid");
    } else {
        uprintf("unknown command, try 'help'\r\n");
    }
}

static void console_task(void)
{
    static char line[64];
    static uint8_t ll;
    while (rxt != rxh) {
        char c = (char)rxbuf[rxt];
        rxt = (uint16_t)((rxt + 1u) & 255u);
        if (c == '\r' || c == '\n') {
            if (ll) { line[ll] = 0; ll = 0; handle_line(line); }
        } else if (ll < sizeof(line) - 1u) {
            line[ll++] = c;
        }
    }
}

/* ------------------------------------------------------------------ entry points */
void esc_early_init(void)
{
    /* why did the MCU (re)start? read before anything else, then clear the flags */
    uint32_t c = RCC->CSR;
    reset_cause = (c & RCC_CSR_IWDGRSTF) ? "independent watchdog" : (c & RCC_CSR_WWDGRSTF) ? "window watchdog" :
                  (c & RCC_CSR_BORRSTF)  ? "brown-out / power-on (supply dip)" : (c & RCC_CSR_SFTRSTF) ? "software reset (e.g. after a HardFault)" :
                  (c & RCC_CSR_LPWRRSTF) ? "low-power reset" : (c & RCC_CSR_OBLRSTF) ? "option byte load" :
                  (c & RCC_CSR_PINRSTF)  ? "reset pin / debugger" : "unknown";
    RCC->CSR |= RCC_CSR_RMVF;
    hw_early_init();
}

void esc_app_init(void)
{
    if (SystemCoreClock != SYSCLK_HZ) {            /* wrong CubeMX clock setup: refuse to run, blink red */
        for (;;) { hw_led_set(1); HAL_Delay(100); hw_led_set(0); HAL_Delay(100); }
    }
    hw_init();
#if OPAMP_FROM_CUBEMX
    HAL_OPAMP_Start(&hopamp1);
    HAL_OPAMP_Start(&hopamp2);
    HAL_OPAMP_Start(&hopamp3);
    HAL_Delay(5);
#endif
    motor_init();
    flash_image_t img;
    bool have_image = flash_image_load(&img);
    params_from_flash = have_image && img.par_valid;
    if (params_from_flash) g_par = img.par;
    hw_led_set(7);                                  /* white for a moment: alive */
    HAL_Delay(300);
    hw_led_set(0);
    g_vbus = hw_vbus_v();
    params_derive(&g_par, g_vbus, &g_eff);
    /* current sampling: hardware trigger from TIM1 (TRGO2 = OC4REF first, then CC4). Accepted only if the samples arrive once
     * per PWM period and right at the PWM peak; otherwise fall back to the software start from the TIM1 CC4 interrupt. */
    static const uint32_t trig[] = { ADC_TRIG_TRGO2, ADC_TRIG_CC4 };
    bool cal_ok = false;
    for (unsigned i = 0; i < sizeof(trig) / sizeof(trig[0]) && !cal_ok; i++) {
        hw_adc_use_hw_trigger(trig[i]);
        cal_ok = motor_calibrate_offsets() && motor_trigger_timing_ok();
    }
    if (!cal_ok) {
        hw_adc_use_software_trigger();
        cal_ok = motor_calibrate_offsets();
    }
    adc_fail = !cal_ok;                             /* keep running so the USB console works for diagnostics */
    if (cal_ok && have_image && img.cal_valid) {    /* offsets stored with 'zero' win over the boot measurement */
        motor_set_offsets(img.cs_offset);
        offsets_from_flash = true;
    }
}

void esc_app_loop(void)
{
    slow_task();
    console_task();
    enc_task();
    spi_speed_task();
    stream_task();
    cal_task();
    led_task();
}
