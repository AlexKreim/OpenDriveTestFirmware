void esc_usb_rx(const uint8_t *b, uint32_t n)
{
    last_rx_ms = HAL_GetTick();
    for (uint32_t i = 0; i < n; i++) {
        uint16_t nx = (uint16_t)((rxh + 1u) & 255u);
        if (nx != rxt) { rxbuf[rxh] = b[i]; rxh = nx; }
    }
}

static void uprintf(const char *fmt, ...)
{
    static char buf[256];
    if (hUsbDeviceFS.dev_state != USBD_STATE_CONFIGURED) return;
    USBD_CDC_HandleTypeDef *hc = (USBD_CDC_HandleTypeDef *)hUsbDeviceFS.pClassData;
    if (hc == NULL) return;
    uint32_t t0 = HAL_GetTick();
    while (hc->TxState != 0 && (HAL_GetTick() - t0) < 50) { }
    if (hc->TxState != 0) return;
    va_list ap;
    va_start(ap, fmt);
    int n = vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    if (n > 0) { if (n > 255) n = 255; CDC_Transmit_FS((uint8_t *)buf, (uint16_t)n); }
}

/* float -> "123.456" without needing printf-float support */
static const char *ff(float v)
{
    static char b[16][20];
    static uint8_t k;
    char *o = b[k++ % 16u];
    long m = (long)(v * 1000.0f + (v < 0 ? -0.5f : 0.5f));
    const char *s = (m < 0) ? "-" : "";
    if (m < 0) m = -m;
    snprintf(o, 20, "%s%ld.%03ld", s, m / 1000, m % 1000);
    return o;
}

/* ------------------------------------------------------------------ LED status */
static bool led_manual;
static bool adc_fail;      /* phase-current ADC triggers missing at boot */

static void led_task(void)
{
    static uint32_t last;
    uint32_t now = HAL_GetTick();
    if (led_manual || (now - last) < 100) return;
    last = now;
    if (adc_fail) { hw_led_set(((now / 250) & 1u) ? 3u : 1u); return; }   /* slow red / yellow = ADC trigger problem */
    switch (g_state) {
    case ST_FAULT:  hw_led_set(((now / 100) & 1u) ? 1u : 0u); break;       /* fast red blink */
    case ST_IDLE:   hw_led_set(((now / 500) & 1u) ? 2u : 0u); break;       /* slow green blink */
    default:        hw_led_set(4u); break;                                 /* blue = motor active */
    }
}

/* ------------------------------------------------------------------ slow task (10 ms) */
static float temp_drv = -999.0f, temp_mot = -999.0f;

static uint8_t uv_count;
static uint8_t ot_src;           /* 0 none, 1 driver, 2 motor (last overtemperature fault) */
static float   ot_val;
static float   uv_vbus;          /* bus voltage at the last undervoltage fault */

/* AS5047P angle: 4 reads averaged on the circle (the sensor itself is ~0.1 deg RMS, this halves the readout noise) */
static uint16_t read_angle(bool *err)
{
    uint16_t first = 0;
    if (motor_foc_active()) {                       /* the control interrupt owns the SPI: use its latest angle */
        uint16_t a;
        bool ok = motor_angle(&a);
        *err = !ok;
        return ok ? a : 0;
    }
    int32_t sum = 0;
    int n = 0;
    *err = false;
    for (int i = 0; i < 4; i++) {
        bool e;
        uint16_t a = hw_as5047_read(0x3FFF, &e);
        if (e) continue;
        if (n == 0) first = a;
        int32_t d = (int32_t)a - (int32_t)first;
        if (d > 8192) d -= 16384; else if (d < -8192) d += 16384;
        sum += d; n++;
    }
    if (n == 0) { *err = true; return 0; }
    int32_t r = (int32_t)first + (sum + (sum >= 0 ? n / 2 : -n / 2)) / n;
    return (uint16_t)(r & 0x3FFF);
}

static void slow_task(void)
{
    static uint32_t last, n;
    uint32_t now = HAL_GetTick();
    if ((now - last) < 10) return;
    last = now;

    g_vbus = hw_vbus_v();
    params_derive(&g_par, g_vbus, &g_eff);
    if ((n++ % 10u) == 0) { temp_drv = hw_temp_driver_c(); temp_mot = hw_temp_motor_c(); }

    esc_state_t s = g_state;
    if (s == ST_PRECHARGE || s == ST_ALIGN || s == ST_RUN || s == ST_CALIB) {
        if (g_vbus < VBUS_MIN_V) { if (uv_count < 255u) uv_count++; } else uv_count = 0;
        if (g_vbus > VBUS_MAX_V)      motor_fault(FLT_OVERVOLT);
        else if (uv_count >= VBUS_UV_SAMPLES) { uv_vbus = g_vbus; motor_fault(FLT_UNDERVOLT); }
        /* the GUI sends 'ping' regularly; if it disappears (crash, unplugged cable) the motor is stopped */
        /* signed difference: the USB interrupt may store a tick newer than 'now' (read earlier in this function); unsigned, that
         * difference wrapped to ~4 billion ms and stopped the motor at random */
        int32_t since_rx = (int32_t)(now - last_rx_ms);
        if (wd_ms != 0u && since_rx > (int32_t)wd_ms) {
            if (motor_running()) stop_reason = "host watchdog (no message from the PC)";
            motor_stop();
            uprintf("INFO: motor stopped by the host watchdog (nothing received for %lu ms)\r\n", (unsigned long)since_rx);
        }
    } else {
        uv_count = 0;
    }
    /* temperature protection is active in every state (also idle: the fault then blocks 'start' until it is cleared and cool) */
    if (g_state != ST_FAULT) {
        if (g_par.ot_drv_en && (temp_drv < -900.0f || temp_drv > g_par.ot_drv_c)) { ot_src = 1; ot_val = temp_drv; motor_fault(FLT_OVERTEMP); }
        else if (g_par.ot_mot_en && (temp_mot < -900.0f || temp_mot > g_par.ot_mot_c)) { ot_src = 2; ot_val = temp_mot; motor_fault(FLT_OVERTEMP); }
    }
}

/* ------------------------------------------------------------------ encoder stream */
static bool     enc_stream;
static uint32_t enc_period = 100;
static uint16_t enc_last_abi;
static int32_t  enc_total;       /* unwrapped ABI counts since the stream started */

static void enc_task(void)
{
    static uint32_t last;
    if (!enc_stream) return;
    uint32_t now = HAL_GetTick();
    if ((now - last) < enc_period) return;
    last = now;

    bool err;
    uint16_t spi = read_angle(&err);                          /* ANGLECOM, 14 bit absolute */
    uint16_t abi = hw_enc_count();
    enc_total += (int16_t)(uint16_t)(abi - enc_last_abi);     /* follow the 16-bit counter without wrap jumps */
    enc_last_abi = abi;

    int32_t pos = enc_total % (int32_t)ENC_CPR;
    if (pos < 0) pos += (int32_t)ENC_CPR;
    float spi_deg = (float)spi * 360.0f / 16384.0f;
    float abi_deg = (float)pos * 360.0f / (float)ENC_CPR;
    float off = spi_deg - abi_deg;                            /* constant while turning if both agree */
    if (off > 180.0f)  off -= 360.0f;
    if (off < -180.0f) off += 360.0f;

    uprintf("SPI %s deg (%5u)%s | ABI cnt %5u, rel %s deg, turns %ld | SPI-ABI %s deg | pins A%u B%u I%u\r\n",
            ff(spi_deg), (unsigned)spi, err ? " ERR" : "", (unsigned)abi, ff(abi_deg),
            (long)(enc_total / (int32_t)ENC_CPR), ff(off),
            (unsigned)((GPIOC->IDR >> 6) & 1u), (unsigned)((GPIOC->IDR >> 7) & 1u), (unsigned)((GPIOD->IDR >> 2) & 1u));
}

/* ------------------------------------------------------------------ speed from the SPI angle */
static float rpm_spi;            /* independent of the ABI counter: unwrapped every 2 ms (unambiguous up to 15000 rpm), averaged over 50 ms */

static void spi_speed_task(void)
{
    static uint32_t last, t0;
    static uint16_t prev;
    static int32_t acc;
    static bool init;
    uint32_t now = HAL_GetTick();
    if ((now - last) < 2u) return;
    bool err;
    uint16_t a = read_angle(&err);
    if (err) return;
    last = now;
    if (!init) { init = true; prev = a; t0 = now; acc = 0; return; }
    int32_t d = (int32_t)a - (int32_t)prev;
    if (d > 8192) d -= 16384; else if (d < -8192) d += 16384;
    acc += d; prev = a;
    uint32_t dt = now - t0;
    if (dt >= 50u) {
        rpm_spi = (float)acc * (60000.0f / 16384.0f) / (float)dt;
        acc = 0; t0 = now;
    }
}

/* ------------------------------------------------------------------ telemetry stream for the GUI */
static uint32_t stream_period;       /* ms, 0 = off */
#define MILLI(x) ((long)((x) * 1000.0f + (((x) < 0.0f) ? -0.5f : 0.5f)))
#define CENTI(x) ((long)((x) * 100.0f + (((x) < 0.0f) ? -0.5f : 0.5f)))

